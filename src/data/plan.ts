export const ADVANCED_FROM_DAY = 17;

export function workoutForDay(day: number): { type: WorkoutType; stage: Stage } {
  return {
    type: CYCLE[(day - 1) % 7],
    stage: day >= ADVANCED_FROM_DAY ? 'advanced' : 'base',
  };
}
export const isDeepWorkDay = (day: number) => day % 7 === 6;
export const isReviewDay = (day: number) => day % 7 === 0;
